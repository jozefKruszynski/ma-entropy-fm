LIFE_ROW_MIN = 8
LIFE_ROW_RANGE = 8
# the rings of the day: the width of each segment is a floor plus a reach times its level, the limit is the level it needs
RING_PRESENCE_REACH = 42
RING_PRESENCE_FLOOR = 8
RING_LIGHT_REACH = 26
RING_LIGHT_FLOOR = 5
