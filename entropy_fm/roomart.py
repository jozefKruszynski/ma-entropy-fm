"""
Images of the artists: a room, or the whole house, drawn from its week in the look of the covers.

An artist is an area of Home Assistant. Its square image has the gradient of the covers in a
palette that belongs to the room (seeded by the area id, so it never changes), a large white
line-art figure cropped off the top and right edges, and the name of the room set lower left like
the title of a cover. The wide image for the backdrop of the artist page has the same palette and
figure, and no text.

The figure is drawn from the typical day of the room, in one of three shapes that the area id picks
(the whole house is always the clock). The clock has 24 spokes, one per hour, as long as the
presence (motion, doors, CO2) in that hour; a wave round it for the lights; small rings inside for
the appliances and the media. It is made from the history of the last days of the room that is
already kept, so nothing is read from Home Assistant for it. A room without kept history gets a
figure of the same kind from its id alone. The whole house has the same figure from all of its
rooms, with a second ring of spokes and ripples. The other shapes are a chart of 24 bars and three
concentric rings of segments. Everything is drawn, nothing is generated by a
model.
"""

from __future__ import annotations

import colorsys
import hashlib
from dataclasses import dataclass, field
from io import BytesIO
from typing import TYPE_CHECKING

import numpy as np

from .baseline import POWER_KINDS, episodes
from .const import WHOLE_HOUSE_ID
from .covers import SIZE, SUPERSAMPLE, Op, _arc, _background, _draw_ops, _hex, _wave_ops
from .timeline import BINARY_KINDS, VoiceKind, stable_hash

if TYPE_CHECKING:
    from collections.abc import Callable, Sequence

    from .timeline import Series

WIDE_WIDTH = 1820
WIDE_HEIGHT = SIZE
HOURS = 24
# what plays a part in which band of the clock
PRESENCE_KINDS = frozenset({VoiceKind.PLUCK, VoiceKind.BLIP, VoiceKind.AIR})
LIGHT_KINDS = frozenset({VoiceKind.CHORD})
LIFE_KINDS = frozenset(
    {
        VoiceKind.MEDIA,
        VoiceKind.COVER,
        VoiceKind.HOB,
        VoiceKind.PHASE,
        *POWER_KINDS,
    }
)
# a band weaker than this (of its own strongest hour, in whole days) is left out
QUIET = 0.04


@dataclass(frozen=True)
class RoomProfile:
    """The typical day of a room: for each hour, how much presence, light and life, each 0 to 1."""

    presence: np.ndarray = field(default_factory=lambda: np.zeros(HOURS))
    light: np.ndarray = field(default_factory=lambda: np.zeros(HOURS))
    life: np.ndarray = field(default_factory=lambda: np.zeros(HOURS))
    # how many days it is made from; 0 for a figure made from the id alone
    days: int = 0

    def digest(self) -> str:
        """Return a short text that changes when the profile does, to name the image by."""
        data = np.round(np.concatenate([self.presence, self.light, self.life]), 2)
        return hashlib.sha256(data.tobytes()).hexdigest()[:10]


def _hour_cover(start: float, end: float, out: np.ndarray) -> None:
    """Add to each hour of the day how much of it the stretch from start to end (seconds) covers."""
    for hour in range(int(start // 3600), min(HOURS, int(end // 3600) + 1)):
        lap = min(end, (hour + 1) * 3600.0) - max(start, hour * 3600.0)
        if lap > 0:
            out[hour] += lap / 3600.0


def _movement(series: Series, out: np.ndarray) -> None:
    """Add to each hour how much the value moved in it (a sensor that has no episodes)."""
    moved = np.abs(np.diff(series.norm))
    for index in np.flatnonzero(moved > 0.1) + 1:
        out[int(series.times[index] // 3600) % HOURS] += min(1.0, float(moved[index - 1]))


def _level(series: Series, out: np.ndarray) -> None:
    """Add to each hour how far above its lowest the sensor stood on average (CO2: how many are in)."""
    mid = (np.arange(HOURS) + 0.5) * 3600.0
    at = np.clip(np.searchsorted(series.times, mid, side="right") - 1, 0, len(series.times) - 1)
    stood = series.norm[at]
    out += np.clip(stood - float(stood.min()), 0.0, 1.0)


def _smooth(values: np.ndarray) -> np.ndarray:
    """Blur a day round the clock a little, so that one hour does not stand alone."""
    return np.asarray(0.25 * np.roll(values, 1) + 0.5 * values + 0.25 * np.roll(values, -1))


def _band(values: np.ndarray) -> np.ndarray:
    """Return a band as 0 to 1 of its own strongest hour; nothing at all when it is quiet."""
    peak = float(values.max())
    if peak <= QUIET:
        return np.zeros(HOURS)
    return np.asarray(np.clip(values / peak, 0.0, 1.0) ** 0.85)


def _add_series(series: Series, bands: dict[str, np.ndarray]) -> bool:
    """Add one entity of one day to the band it belongs to; return whether it played a part."""
    if len(series.times) < 2:
        return False
    if series.kind in PRESENCE_KINDS:
        band = bands["presence"]
    elif series.kind in LIGHT_KINDS:
        band = bands["light"]
    elif series.kind in LIFE_KINDS:
        band = bands["life"]
    else:
        return False
    if series.kind in BINARY_KINDS or series.kind in POWER_KINDS:
        for start, end in episodes(series):
            _hour_cover(start, end, band)
    elif series.kind == VoiceKind.AIR:
        _level(series, band)
    else:
        _movement(series, band)
    return True


def week_profile(days: Sequence[Sequence[Series]]) -> RoomProfile | None:
    """
    Make the typical day of a room from the series of some days.

    :param days: For each day the series of the room (or of every room of the house).
    :returns: The profile, or None when the days have nothing to draw from.
    """
    bands = {"presence": np.zeros(HOURS), "light": np.zeros(HOURS), "life": np.zeros(HOURS)}
    count = sum(1 for day in days if sum(_add_series(series, bands) for series in day))
    if not count:
        return None
    made = {name: _band(_smooth(values / count)) for name, values in bands.items()}
    if not any(float(values.max()) > 0 for values in made.values()):
        return None
    return RoomProfile(made["presence"], made["light"], made["life"], count)


def seeded_profile(area_id: str) -> RoomProfile:
    """Return a figure of the same kind from the id alone, for a room that has no history kept yet."""
    rng = np.random.default_rng(stable_hash("room-profile", area_id) % 2**32)
    hours = np.arange(HOURS, dtype=np.float64)

    def bumps(count: int, low: float, high: float, width: float) -> np.ndarray:
        total = np.zeros(HOURS)
        for _ in range(count):
            at, weight = rng.uniform(low, high), rng.uniform(0.4, 1.0)
            gap = np.abs((hours - at + 12) % 24 - 12)
            total += weight * np.exp(-((gap / width) ** 2))
        return total

    presence = bumps(int(rng.integers(2, 4)), 6.0, 22.0, float(rng.uniform(1.3, 2.4)))
    light = bumps(int(rng.integers(1, 3)), 16.0, 23.0, float(rng.uniform(2.0, 3.5)))
    light += 0.25 * bumps(1, 5.0, 8.0, 1.5)
    life = bumps(int(rng.integers(2, 5)), 7.0, 22.0, 0.8)
    return RoomProfile(_band(presence), _band(light), _band(life), 0)


# -- the figure: the drawing operations of the covers, centred on (0, 0) ---------------------------

HUB = 118
SPOKE_FROM = 150
SPOKE_REACH = 230
LIGHT_RADIUS = 410
LIFE_RADIUS = 480


def _polar(radius: float, hour: float) -> tuple[float, float]:
    """Return the point at a radius and an hour of the clock (0 at the top, clockwise)."""
    angle = np.radians(-90.0 + 15.0 * hour)
    return radius * float(np.cos(angle)), radius * float(np.sin(angle))


def _figure(profile: RoomProfile, *, rich: bool) -> list[Op]:
    """
    Return the clock of a day as drawing operations, about 1000 units wide.

    The spokes are the presence of each hour (quiet hours are dots, the busiest is the accent), the arcs
    round them are the lights, thicker where they burn more, and the discs on the rim are the appliances
    and the media.

    :param profile: The typical day.
    :param rich: Whether to draw the richer figure of the whole house.
    """
    ops: list[Op] = [("ring", 0, 0, HUB, 26, "w", 1.0), ("ring", 0, 0, HUB - 40, 7, "w", 0.8)]
    top = int(np.argmax(profile.presence)) if float(profile.presence.max()) > 0 else -1
    for hour in range(HOURS):
        level = float(profile.presence[hour])
        if level <= QUIET:
            x, y = _polar(SPOKE_FROM + 18, hour + 0.5)
            ops.append(("disc", x, y, 8, "w"))
            continue
        reach = SPOKE_FROM + 36 + SPOKE_REACH * level
        width = 30 if hour % 6 == 0 else 20
        ops.append(
            (
                "line",
                [_polar(SPOKE_FROM, hour + 0.5), _polar(reach, hour + 0.5)],
                width,
                "a" if hour == top else "w",
                1.0,
            )
        )
    for hour in range(HOURS):
        level = float(profile.light[hour])
        if level > QUIET:
            arc = _arc(0, 0, LIGHT_RADIUS, -90 + 15 * hour + 1.5, -90 + 15 * (hour + 1) - 1.5, 10)
            ops.append(("line", arc, 6 + 14 * level, "w", 1.0))
        level = float(profile.life[hour])
        if level > 0.2:
            x, y = _polar(LIFE_RADIUS, hour + 0.5)
            ops.append(("disc", x, y, 8 + 12 * level, "w"))
    if rich:
        for hour in range(HOURS):
            level = float(profile.light[hour])
            if level > QUIET:
                a, b = _polar(18, hour + 0.5), _polar(18 + 52 * level, hour + 0.5)
                ops.append(("line", [a, b], 9, "w", 0.9))
        ops.extend(
            ("ring", 0, 0, 540 + 46 * index, 5, "w", 0.7 - 0.2 * index) for index in range(2)
        )
        ops.append(("disc", 0, 0, 14, "a"))
    return ops


BAR_PITCH = 34
BAR_WIDTH = 20
BAR_BASE = 230
BAR_REACH = 280
LIGHT_DROP = 150
LIFE_ROW = 440
RING_PRESENCE = 210
RING_LIGHT = 330
RING_LIFE = 440
RING_GAP = 3.0
SHAPE_CLOCK = "clock"
SHAPE_BARS = "bars"
SHAPE_RINGS = "rings"
SHAPES = (SHAPE_CLOCK, SHAPE_BARS, SHAPE_RINGS)


def _bars(profile: RoomProfile) -> list[Op]:
    """
    Return the day as a chart of 24 bars standing on a baseline, midnight on the left.

    The bars are the presence of each hour (the busiest is the accent, quiet hours are dots), the
    thinner bars hanging below are the lights, and the discs in the row under them the appliances
    and the media.

    :param profile: The typical day.
    """
    left = -BAR_PITCH * (HOURS - 1) / 2
    ops: list[Op] = [("line", [(left - 30, BAR_BASE), (-left + 30, BAR_BASE)], 8, "w", 0.8)]
    top = int(np.argmax(profile.presence)) if float(profile.presence.max()) > 0 else -1
    for hour in range(HOURS):
        x = left + BAR_PITCH * hour
        level = float(profile.presence[hour])
        if level <= QUIET:
            ops.append(("disc", x, BAR_BASE - 22, 8, "w"))
        else:
            height = 40 + BAR_REACH * level
            ops.append(
                (
                    "line",
                    [(x, BAR_BASE - 12), (x, BAR_BASE - 12 - height)],
                    BAR_WIDTH,
                    "a" if hour == top else "w",
                    1.0,
                )
            )
        level = float(profile.light[hour])
        if level > QUIET:
            ops.append(
                (
                    "line",
                    [(x, BAR_BASE + 28), (x, BAR_BASE + 28 + LIGHT_DROP * level)],
                    10,
                    "w",
                    0.9,
                )
            )
        level = float(profile.life[hour])
        if level > 0.2:
            ops.append(("disc", x, LIFE_ROW, 8 + 8 * level, "w"))
    return ops


def _rings(profile: RoomProfile) -> list[Op]:
    """
    Return the day as three concentric rings of 24 segments, midnight at the top, clockwise.

    The inner ring is the presence of each hour, the middle one the lights, and the outer one the
    appliances and the media; the thicker a segment, the more of it in that hour.

    :param profile: The typical day.
    """
    ops: list[Op] = [("ring", 0, 0, HUB, 26, "w", 1.0), ("ring", 0, 0, HUB - 40, 7, "w", 0.8)]
    top = int(np.argmax(profile.presence)) if float(profile.presence.max()) > 0 else -1
    for radius, band, reach, floor, limit in (
        (RING_PRESENCE, profile.presence, 42, 8, QUIET),
        (RING_LIGHT, profile.light, 26, 5, QUIET),
        (RING_LIFE, profile.life, 22, 5, 0.2),
    ):
        ops.append(("ring", 0, 0, radius, 3, "w", 0.5))
        for hour in range(HOURS):
            level = float(band[hour])
            if level <= limit:
                continue
            arc = _arc(
                0, 0, radius, -90 + 15 * hour + RING_GAP, -90 + 15 * (hour + 1) - RING_GAP, 10
            )
            accent = band is profile.presence and hour == top
            ops.append(("line", arc, floor + reach * level, "a" if accent else "w", 1.0))
    return ops


def figure_shape(area_id: str) -> str:
    """Return the shape of the figure of a room, from its id alone; the whole house is always the clock."""
    if area_id == WHOLE_HOUSE_ID:
        return SHAPE_CLOCK
    return SHAPES[stable_hash("room-shape", area_id) % len(SHAPES)]


def _figure_of(area_id: str, profile: RoomProfile) -> list[Op]:
    """Return the figure of a room, in the shape that its id picks."""
    shape = figure_shape(area_id)
    if shape == SHAPE_BARS:
        return _bars(profile)
    if shape == SHAPE_RINGS:
        return _rings(profile)
    return _figure(profile, rich=area_id == WHOLE_HOUSE_ID)


# -- the palette and the images ------------------------------------------------------------------


def room_colours(area_id: str) -> list[str]:
    """
    Return the dark, middle and bright colour of the gradient of a room, and its accent.

    The hue comes from the area id alone, so a room keeps its colours; the whole house is amber.
    """
    hue = 0.09 if area_id == WHOLE_HOUSE_ID else (stable_hash("room-hue", area_id) % 360) / 360.0
    shades = (
        (hue, 0.78, 0.27),
        ((hue + 0.04) % 1.0, 0.62, 0.55),
        ((hue - 0.05) % 1.0, 0.36, 0.93),
        ((hue + 0.5) % 1.0, 0.30, 1.0),
    )
    return [_hex(np.array([255 * c for c in colorsys.hsv_to_rgb(h, s, v)])) for h, s, v in shades]


def _composite(  # noqa: PLR0913, PLR0917
    colours: list[str],
    rng: np.random.Generator,
    figure: list[Op],
    place: Callable[[float, float], tuple[float, float]],
    scale: float,
    width: int,
    height: int,
) -> np.ndarray:
    """Draw the gradient, the figure and the grain, as float RGB."""
    from PIL import Image  # noqa: PLC0415

    angle = float(rng.random()) * 80
    bloom = (0.55 + 0.3 * float(rng.random()), 0.12 + 0.28 * float(rng.random()))
    canvas = _background(colours[:3], angle, bloom, height, width)
    turn = float(rng.random()) * 12 - 6
    white, accent = _draw_ops(figure, place, scale, turn, height * SUPERSAMPLE, width * SUPERSAMPLE)
    # the dots-to-wave of the icon, as on the covers
    dots, wave = _wave_ops()
    small, _ = _draw_ops(
        [*dots, *wave], lambda x, y: (x, y), 1.0, 0.0, height * SUPERSAMPLE, width * SUPERSAMPLE
    )
    box = Image.Resampling.BOX
    mask_w = (
        np.maximum(
            np.asarray(white.resize((width, height), box), dtype=np.float32),
            np.asarray(small.resize((width, height), box), dtype=np.float32),
        )[..., None]
        / 255.0
    )
    mask_a = np.asarray(accent.resize((width, height), box), dtype=np.float32)[..., None] / 255.0
    accent_rgb = np.array([int(colours[3][i : i + 2], 16) for i in (1, 3, 5)], dtype=np.float32)
    canvas = canvas * (1 - mask_w) + 255.0 * mask_w
    canvas = canvas * (1 - mask_a) + accent_rgb * mask_a
    canvas += rng.normal(0.0, 2.2, (height, width, 1)).astype(np.float32)
    return np.asarray(canvas)


def _jpeg(canvas: np.ndarray) -> bytes:
    """Return a picture as a JPEG."""
    from PIL import Image  # noqa: PLC0415

    out = BytesIO()
    Image.fromarray(np.clip(canvas, 0, 255).astype(np.uint8), "RGB").save(
        out, "JPEG", optimize=True, quality=90
    )
    return out.getvalue()


def artist_thumb(area_id: str, name: str, profile: RoomProfile, *, title: bool = True) -> bytes:
    """
    Draw the square image of a room as a 1024 pixel JPEG.

    :param area_id: The id of the area; the palette and the small variations come from it.
    :param name: The name of the room, which is the title.
    :param profile: The typical day of the room, see `week_profile` and `seeded_profile`.
    :param title: Whether to set the name lower left, as on the covers.
    """
    from PIL import Image  # noqa: PLC0415

    from .maart import draw_title_on  # noqa: PLC0415

    rng = np.random.default_rng(stable_hash("room-thumb", area_id) % 2**32)
    gx, gy = 570 + float(rng.integers(0, 80)), 280 + float(rng.integers(0, 50))
    scale = 1.05 + 0.2 * float(rng.random())
    canvas = _composite(
        room_colours(area_id),
        rng,
        _figure_of(area_id, profile),
        lambda x, y: (gx + x, gy + y),
        scale,
        SIZE,
        SIZE,
    )
    image = Image.fromarray(np.clip(canvas, 0, 255).astype(np.uint8), "RGB")
    if title:
        image = draw_title_on(image, name)
    out = BytesIO()
    image.save(out, "JPEG", optimize=True, quality=90)
    return out.getvalue()


def artist_fanart(area_id: str, profile: RoomProfile) -> bytes:
    """
    Draw the wide image behind the page of a room as a JPEG, 1820 by 1024 pixels, without text.

    :param area_id: The id of the area; the palette and the small variations come from it.
    :param profile: The typical day of the room, see `week_profile` and `seeded_profile`.
    """
    rng = np.random.default_rng(stable_hash("room-fanart", area_id) % 2**32)
    gx, gy = 1330 + float(rng.integers(0, 80)), 430 + float(rng.integers(-30, 30))
    scale = 1.45 + 0.2 * float(rng.random())
    canvas = _composite(
        room_colours(area_id),
        rng,
        _figure_of(area_id, profile),
        lambda x, y: (gx + x, gy + y),
        scale,
        WIDE_WIDTH,
        WIDE_HEIGHT,
    )
    return _jpeg(canvas)
