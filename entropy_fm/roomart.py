def _line(
    points: list[tuple[float, float]], width: float = WIDTH, colour: str = "w", alpha: float = 1.0
) -> Op:
    return ("line", points, width, colour, alpha)


def _rect(  # noqa: PLR0913, PLR0917
    x0: float,
    y0: float,
    x1: float,
    y1: float,
    radius: float = 30,
    width: float = WIDTH,
    colour: str = "w",
) -> Op:
    """Return a rounded rectangle, stroked."""
    r = min(radius, (x1 - x0) / 2, (y1 - y0) / 2)
    pts = (
        _arc(x1 - r, y1 - r, r, 0, 90, 8)
        + _arc(x0 + r, y1 - r, r, 90, 180, 8)
        + _arc(x0 + r, y0 + r, r, 180, 270, 8)
        + _arc(x1 - r, y0 + r, r, 270, 360, 8)
    )
    return _line([*pts, pts[0]], width, colour)


def _ring(x: float, y: float, radius: float, width: float = WIDTH, colour: str = "w") -> Op:
    return ("ring", x, y, radius, width, colour, 1.0)


