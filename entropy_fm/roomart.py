MODIFIERS = frozenset({"kids", "guest"})


def _plain(text: str) -> str:
    """Return text in lower case without accents, with letters and digits separated by single spaces."""
    flat = unicodedata.normalize("NFKD", text.lower().replace("ß", "ss"))
    flat = "".join(ch for ch in flat if not unicodedata.combining(ch))
    return " ".join(re.sub(r"[^a-z0-9]+", " ", flat).split())


def _first_match(words: tuple[str, ...], text: str) -> int | None:
    """Return where in the text the earliest of the words is, or None; see `NAME_WORDS` for what counts."""
    padded = f" {text} "
    best: int | None = None
    for word in words:
        short = len(word) <= 4 and " " not in word
        needle = f" {word}" if short else word
        at = padded.find(needle)
        if at == -1:
            continue
        # "wc" is a word of its own, not the start of one
        if len(word) <= 2 and padded[at + len(needle) : at + len(needle) + 1] != " ":
            continue
        at += 1 if short else 0
        best = at if best is None else min(best, at)
    return best


def room_kind(name: str, area_id: str = "", icon: str | None = None) -> str:
    """
    Return the kind of a room: from the icon of its area, else from words of its name or id.

    :param name: The name of the area.
    :param area_id: The id of the area, which says the same as the name more often than not.
    :param icon: The icon of the area in Home Assistant, such as `mdi:sofa`.
    :returns: One of the keys of `GLYPHS`; `house` for the whole house, `generic` when unknown.
    """
    if area_id == WHOLE_HOUSE_ID:
        return HOUSE
    if icon:
        kind = ICON_TO_KIND.get(icon.rsplit(":", 1)[-1].strip().lower())
        if kind is not None:
            return kind
    for text in (_plain(name), _plain(area_id)):
        hits = [
            (position, order, kind)
            for order, (kind, words) in enumerate(NAME_WORDS)
            if (position := _first_match(words, text)) is not None
        ]
        if not hits:
            continue
        main = [hit for hit in hits if hit[2] not in MODIFIERS]
        return min(main or hits)[2]
    return GENERIC


